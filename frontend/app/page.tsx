"use client";

import React, { useEffect, useState } from "react";
import {
  Users, UserCheck, UserSearch, FileText, CalendarDays, RefreshCw,
  Briefcase, User, Heart, MessageCircle, Play, Sparkles, TrendingUp,
  Zap, BarChart3, Bot, ChevronDown, ChevronRight,
} from "lucide-react";
import {
  ResponsiveContainer, LineChart, Line, XAxis, YAxis, Tooltip,
  CartesianGrid, Legend,
} from "recharts";

// ─── Types ────────────────────────────────────────────────────────────────

type AccountStats = {
  username: string;
  full_name: string;
  is_business: boolean;
  date_checked: string;
  followers: number;
  following: number;
  total_posts: number;
};

type AggTotals = {
  total_posts: number;
  total_likes: number;
  total_comments: number;
  total_views: number;
};

type ProfilePoint = {
  date_checked: string;
  followers: number;
  following: number;
  total_posts: number;
};

type EngagementPoint = {
  scrape_date: string;
  likes: number;
  comments: number;
  views: number;
  posts_scraped: number;
};

type AccountHistory = {
  profile_history: ProfilePoint[];
  engagement_history: EngagementPoint[];
};

type AiInsights = {
  communityPulse: string;
  viralAnomaly: string;
  sectorMomentum: string[];
};

// ─── Sub-components ───────────────────────────────────────────────────────

function StatCard({ icon: Icon, label, value }: { icon: React.ElementType; label: string; value: string }) {
  return (
    <div className="bg-card border border-border rounded-lg p-5 flex items-start gap-4">
      <div className="p-2.5 rounded-lg bg-primary/10 border border-primary/20 shrink-0">
        <Icon className="w-4 h-4 text-primary" />
      </div>
      <div>
        <p className="text-2xl font-bold text-foreground tabular-nums">{value}</p>
        <p className="text-xs font-medium text-muted-foreground mt-0.5 uppercase tracking-wider">{label}</p>
      </div>
    </div>
  );
}

function AICard({ icon: Icon, badge, title, children }: { icon: React.ElementType; badge: string; title: string; children: React.ReactNode }) {
  return (
    <div className="bg-card border border-border rounded-lg p-6 flex flex-col gap-4">
      <div className="flex items-center gap-2">
        <div className="p-1.5 rounded-md bg-primary/10 border border-primary/20">
          <Icon className="w-3.5 h-3.5 text-primary" />
        </div>
        <span className="text-[10px] font-semibold text-primary uppercase tracking-widest">{badge}</span>
      </div>
      <div>
        <h3 className="font-semibold text-foreground mb-2">{title}</h3>
        {children}
      </div>
      <div className="flex items-center gap-1.5 pt-1 border-t border-border mt-auto">
        <Bot className="w-3 h-3 text-muted-foreground" />
        <span className="text-[10px] text-muted-foreground">Generated by local AI model</span>
      </div>
    </div>
  );
}

const CHART_THEME = {
  grid: "hsl(var(--border))",
  text: "hsl(var(--muted-foreground))",
  followers: "#3b9eff",
  following: "#a78bfa",
  total_posts: "#34d399",
  likes: "#f472b6",
  comments: "#fb923c",
  views: "#60a5fa",
};

const tooltipStyle = {
  backgroundColor: "hsl(var(--popover))",
  border: "1px solid hsl(var(--border))",
  borderRadius: "8px",
  color: "hsl(var(--popover-foreground))",
  fontSize: "12px",
};

function AccountCharts({ username }: { username: string }) {
  const [history, setHistory] = useState<AccountHistory | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    fetch(`http://127.0.0.1:5000/api/account-history/${encodeURIComponent(username)}`)
      .then(r => r.json())
      .then(d => setHistory(d))
      .catch(() => {})
      .finally(() => setLoading(false));
  }, [username]);

  if (loading) return (
    <div className="flex items-center gap-2 p-6 text-muted-foreground text-sm bg-muted/20 border-t border-border">
      <RefreshCw className="w-4 h-4 animate-spin" /> Loading history for @{username}...
    </div>
  );

  const hasProfile = history && history.profile_history.length > 0;
  const hasEngagement = history && history.engagement_history.length > 0;

  if (!hasProfile && !hasEngagement) return (
    <div className="p-6 text-sm text-muted-foreground bg-muted/20 border-t border-border">
      No historical data yet for @{username}.
    </div>
  );

  const profileData = (history?.profile_history ?? []).map(p => ({
    ...p,
    date: new Date(p.date_checked).toLocaleDateString("en-CA", { month: "short", day: "numeric" }),
  }));

  const engagementData = (history?.engagement_history ?? []).map(e => ({
    ...e,
    date: new Date(e.scrape_date).toLocaleDateString("en-CA", { month: "short", day: "numeric" }),
  }));

  return (
    <div className="bg-muted/20 border-t border-border">
      <div className="px-6 pt-5 pb-6 space-y-8">

        {/* History sweep table */}
        {hasProfile && (
          <div>
            <p className="text-xs font-semibold text-muted-foreground uppercase tracking-wider mb-3 flex items-center gap-1.5">
              <CalendarDays className="w-3.5 h-3.5" /> All Recorded Sweeps
            </p>
            <div className="border border-border rounded-md overflow-hidden max-h-48 overflow-y-auto">
              <table className="w-full text-xs">
                <thead>
                  <tr className="bg-muted/60 border-b border-border">
                    <th className="py-2 px-3 text-left font-medium text-muted-foreground">Date</th>
                    <th className="py-2 px-3 text-right font-medium text-muted-foreground">Followers</th>
                    <th className="py-2 px-3 text-right font-medium text-muted-foreground">Following</th>
                    <th className="py-2 px-3 text-right font-medium text-muted-foreground">Total Posts</th>
                  </tr>
                </thead>
                <tbody>
                  {[...history!.profile_history].reverse().map((row, i) => (
                    <tr key={i} className="border-b border-border last:border-0 hover:bg-muted/40 transition-colors">
                      <td className="py-2 px-3 text-muted-foreground">{new Date(row.date_checked).toLocaleString()}</td>
                      <td className="py-2 px-3 text-right font-medium text-foreground tabular-nums">{row.followers.toLocaleString()}</td>
                      <td className="py-2 px-3 text-right text-foreground tabular-nums">{row.following.toLocaleString()}</td>
                      <td className="py-2 px-3 text-right text-foreground tabular-nums">{row.total_posts.toLocaleString()}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
        )}

        {/* Profile growth chart */}
        {hasProfile && profileData.length > 1 && (
          <div>
            <p className="text-xs font-semibold text-muted-foreground uppercase tracking-wider mb-4">
              Profile Growth Trend
            </p>
            <ResponsiveContainer width="100%" height={200}>
              <LineChart data={profileData} margin={{ top: 4, right: 8, left: 0, bottom: 0 }}>
                <CartesianGrid strokeDasharray="3 3" stroke={CHART_THEME.grid} />
                <XAxis dataKey="date" tick={{ fill: CHART_THEME.text, fontSize: 11 }} axisLine={false} tickLine={false} />
                <YAxis tick={{ fill: CHART_THEME.text, fontSize: 11 }} axisLine={false} tickLine={false} width={52} tickFormatter={v => v >= 1000 ? `${(v / 1000).toFixed(0)}k` : String(v)} />
                <Tooltip contentStyle={tooltipStyle} />
                <Legend wrapperStyle={{ fontSize: 11, color: CHART_THEME.text }} />
                <Line type="monotone" dataKey="followers" stroke={CHART_THEME.followers} strokeWidth={2} dot={false} name="Followers" />
                <Line type="monotone" dataKey="following" stroke={CHART_THEME.following} strokeWidth={2} dot={false} name="Following" />
                <Line type="monotone" dataKey="total_posts" stroke={CHART_THEME.total_posts} strokeWidth={2} dot={false} name="Total Posts" />
              </LineChart>
            </ResponsiveContainer>
          </div>
        )}

        {/* Engagement chart */}
        {hasEngagement && engagementData.length > 0 && (
          <div>
            <p className="text-xs font-semibold text-muted-foreground uppercase tracking-wider mb-4">
              Scrape-Day Engagement
            </p>
            <ResponsiveContainer width="100%" height={200}>
              <LineChart data={engagementData} margin={{ top: 4, right: 8, left: 0, bottom: 0 }}>
                <CartesianGrid strokeDasharray="3 3" stroke={CHART_THEME.grid} />
                <XAxis dataKey="date" tick={{ fill: CHART_THEME.text, fontSize: 11 }} axisLine={false} tickLine={false} />
                <YAxis tick={{ fill: CHART_THEME.text, fontSize: 11 }} axisLine={false} tickLine={false} width={52} tickFormatter={v => v >= 1000 ? `${(v / 1000).toFixed(0)}k` : String(v)} />
                <Tooltip contentStyle={tooltipStyle} />
                <Legend wrapperStyle={{ fontSize: 11, color: CHART_THEME.text }} />
                <Line type="monotone" dataKey="likes" stroke={CHART_THEME.likes} strokeWidth={2} dot={false} name="Likes" />
                <Line type="monotone" dataKey="comments" stroke={CHART_THEME.comments} strokeWidth={2} dot={false} name="Comments" />
                <Line type="monotone" dataKey="views" stroke={CHART_THEME.views} strokeWidth={2} dot={false} name="Views" />
              </LineChart>
            </ResponsiveContainer>
          </div>
        )}

      </div>
    </div>
  );
}

// ─── Main Page ────────────────────────────────────────────────────────────

export default function OverviewPage() {
  const [accounts, setAccounts] = useState<AccountStats[]>([]);
  const [totals, setTotals] = useState<AggTotals | null>(null);
  const [loading, setLoading] = useState(true);
  const [expandedAccount, setExpandedAccount] = useState<string | null>(null);
  
  const [aiInsights, setAiInsights] = useState<AiInsights | null>(null);
  const [aiLoading, setAiLoading] = useState(true);

  useEffect(() => {
    Promise.all([
      fetch("http://127.0.0.1:5000/api/accounts").then(r => r.json()),
      fetch("http://127.0.0.1:5000/api/stats").then(r => r.json()),
    ])
      .then(([accountData, statsData]) => {
        setAccounts(accountData.accounts || []);
        setTotals(statsData.totals || null);
      })
      .catch(err => console.error("Failed to fetch overview data", err))
      .finally(() => setLoading(false));

    fetch("http://127.0.0.1:5000/api/ai-insights")
      .then(r => r.json())
      .then(d => {
        if (!d.error) setAiInsights(d);
      })
      .catch(err => console.error("Failed to fetch AI insights", err))
      .finally(() => setAiLoading(false));
  }, []);

  const toggleAccount = (username: string) => {
    setExpandedAccount(prev => prev === username ? null : username);
  };

  return (
    <div className="space-y-10">

      {/* Page header */}
      <div>
        <h1 className="text-2xl font-semibold text-foreground">Local Area Overview</h1>
        <p className="text-muted-foreground mt-1">
          Aggregated intelligence across {accounts.length} monitored accounts in the area.
        </p>
      </div>

      {/* Aggregate stats bar */}
      <section>
        <h2 className="text-xs font-semibold text-muted-foreground uppercase tracking-wider mb-3">Engagement Totals — All Time</h2>
        {loading ? (
          <div className="flex items-center gap-2 text-muted-foreground text-sm"><RefreshCw className="w-4 h-4 animate-spin" /> Loading...</div>
        ) : (
          <div className="grid grid-cols-2 lg:grid-cols-4 gap-4">
            <StatCard icon={FileText} label="Posts Scraped" value={(totals?.total_posts ?? 0).toLocaleString()} />
            <StatCard icon={Heart} label="Total Likes" value={(totals?.total_likes ?? 0).toLocaleString()} />
            <StatCard icon={MessageCircle} label="Total Comments" value={(totals?.total_comments ?? 0).toLocaleString()} />
            <StatCard icon={Play} label="Total Views" value={(totals?.total_views ?? 0).toLocaleString()} />
          </div>
        )}
      </section>

      {/* AI Summary */}
      <section>
        <div className="flex items-center gap-2 mb-4">
          <Sparkles className="w-4 h-4 text-primary" />
          <h2 className="text-xs font-semibold text-muted-foreground uppercase tracking-wider">AI Local Area Intelligence</h2>
          <span className="ml-auto text-[10px] font-medium px-2 py-0.5 rounded-full bg-primary/10 text-primary border border-primary/20">
            {aiLoading ? "Generating Live Local Insight..." : "Live Local Insight"}
          </span>
        </div>
        <div className="grid grid-cols-1 lg:grid-cols-3 gap-5">
          <AICard icon={TrendingUp} badge="Community Pulse" title="Trending Themes This Week">
            {aiLoading ? (
               <div className="flex justify-center py-4"><RefreshCw className="w-5 h-5 text-muted-foreground animate-spin" /></div>
            ) : aiInsights ? (
               <p className="text-sm text-muted-foreground leading-relaxed">{aiInsights.communityPulse}</p>
            ) : (
               <p className="text-sm text-destructive leading-relaxed">Failed to generate intelligence data.</p>
            )}
          </AICard>
          <AICard icon={Zap} badge="Viral Anomaly" title="Breakout Post of the Week">
            {aiLoading ? (
               <div className="flex justify-center py-4"><RefreshCw className="w-5 h-5 text-muted-foreground animate-spin" /></div>
            ) : aiInsights ? (
               <p className="text-sm text-muted-foreground leading-relaxed">{aiInsights.viralAnomaly}</p>
            ) : (
               <p className="text-sm text-destructive leading-relaxed">Failed to generate intelligence data.</p>
            )}
          </AICard>
          <AICard icon={BarChart3} badge="Sector Momentum" title="Who Is Winning the Local Feed?">
            {aiLoading ? (
               <div className="flex justify-center py-4"><RefreshCw className="w-5 h-5 text-muted-foreground animate-spin" /></div>
            ) : aiInsights ? (
               <ul className="space-y-3">
                 {aiInsights.sectorMomentum.map((item, i) => (
                   <li key={i} className="flex items-start gap-2 text-sm">
                     <span className="mt-1.5 w-1.5 h-1.5 rounded-full bg-primary shrink-0" />
                     <span className="leading-relaxed text-muted-foreground">{item}</span>
                   </li>
                 ))}
               </ul>
            ) : (
               <p className="text-sm text-destructive leading-relaxed">Failed to generate intelligence data.</p>
            )}
          </AICard>
        </div>
      </section>

      {/* Monitored Accounts + expandable charts */}
      <section>
        <h2 className="text-xs font-semibold text-muted-foreground uppercase tracking-wider mb-3">Monitored Accounts</h2>
        <div className="bg-card border border-border rounded-lg overflow-hidden shadow-sm">
          {loading ? (
            <div className="p-8 text-center text-muted-foreground flex items-center justify-center gap-2">
              <RefreshCw className="w-4 h-4 animate-spin" /> Loading metrics...
            </div>
          ) : (
          <table className="w-full text-sm">
              <thead>
                <tr className="bg-muted/50 border-b border-border">
                  <th className="py-3 px-2 w-8" />
                  <th className="py-3 px-4 text-left font-medium text-muted-foreground">
                    <span className="flex items-center gap-1.5"><UserSearch className="w-3.5 h-3.5" />Target</span>
                  </th>
                  <th className="py-3 px-4 text-left font-medium text-muted-foreground">
                    <span className="flex items-center gap-1.5"><Briefcase className="w-3.5 h-3.5" />Type</span>
                  </th>
                  <th className="py-3 px-4 text-left font-medium text-muted-foreground">
                    <span className="flex items-center gap-1.5"><Users className="w-3.5 h-3.5" />Followers</span>
                  </th>
                  <th className="py-3 px-4 text-left font-medium text-muted-foreground">
                    <span className="flex items-center gap-1.5"><UserCheck className="w-3.5 h-3.5" />Following</span>
                  </th>
                  <th className="py-3 px-4 text-left font-medium text-muted-foreground">
                    <span className="flex items-center gap-1.5"><FileText className="w-3.5 h-3.5" />Posts</span>
                  </th>
                  <th className="py-3 px-4 text-left font-medium text-muted-foreground">
                    <span className="flex items-center gap-1.5"><CalendarDays className="w-3.5 h-3.5" />Last Checked</span>
                  </th>
                </tr>
              </thead>
              <tbody>
                {accounts.map((item) => (
                  <React.Fragment key={item.username}>
                    <tr
                      onClick={() => toggleAccount(item.username)}
                      className="border-b border-border hover:bg-muted/50 transition-colors cursor-pointer"
                    >
                      <td className="py-3 px-2 text-center text-muted-foreground">
                        {expandedAccount === item.username
                          ? <ChevronDown className="w-3.5 h-3.5 mx-auto" />
                          : <ChevronRight className="w-3.5 h-3.5 mx-auto" />
                        }
                      </td>
                      <td className="py-3 px-4 font-medium text-foreground">@{item.username}</td>
                      <td className="py-3 px-4">
                        {item.is_business ? (
                          <span className="inline-flex items-center gap-1 bg-primary/20 text-primary px-2 py-0.5 rounded text-xs font-medium border border-primary/30">
                            <Briefcase className="w-3 h-3" />Business
                          </span>
                        ) : (
                          <span className="inline-flex items-center gap-1 bg-muted-foreground/10 text-muted-foreground px-2 py-0.5 rounded text-xs font-medium border border-muted-foreground/20">
                            <User className="w-3 h-3" />Creator
                          </span>
                        )}
                      </td>
                      <td className="py-3 px-4 text-card-foreground tabular-nums">{item.followers?.toLocaleString() ?? "0"}</td>
                      <td className="py-3 px-4 text-card-foreground tabular-nums">{item.following?.toLocaleString() ?? "0"}</td>
                      <td className="py-3 px-4 text-card-foreground tabular-nums">{item.total_posts?.toLocaleString() ?? "0"}</td>
                      <td className="py-3 px-4 text-muted-foreground text-xs">
                        {item.date_checked ? new Date(item.date_checked).toDateString() : "Never"}
                      </td>
                    </tr>
                    {expandedAccount === item.username && (
                      <tr key={`${item.username}-charts`} className="border-b border-border">
                        <td colSpan={7} className="p-0">
                          <AccountCharts username={item.username} />
                        </td>
                      </tr>
                    )}
                  </React.Fragment>
                ))}
              </tbody>
            </table>
          )}
        </div>
        <p className="text-xs text-muted-foreground mt-2">Click any row to expand its historical trend charts.</p>
      </section>

    </div>
  );
}
